void delay()
{
    for (volatile long i = 0; i < 500; i++) {} //loopar 500 ggr f?r o pausa lite
}


void draw_icon(struct RastPort* rp, int iconIndex, int startX, int startY)
{

    for (int y = 0; y < ICON_HEIGHT; y++) { //forloopar f?r o rita iconer
        for (int x = 0; x < ICON_WIDTH; x++) {
            UBYTE color = iconSet[iconIndex][y][x]; //plockar f?rgcoder fr?n arrayet iconset
            if (color != 0) {                           //ritar inga pixlr p? 0:or
                SetAPen(rp, color); //st?ller in f?rg o rita med
                WritePixel(rp, startX + x, startY + y); //ritar en pixel
            }
        }
    }

}

void draw_background(struct RastPort* rp)
{
    SetAPen(rp, 1); // st?ller in f?rg
    Move(rp, 10, 10);//startposition
    Draw(rp, 50, 10);//ritar ett sreck fr?n starten

    SetAPen(rp, 1); // vit text
    Move(rp, 10, 8);
    Text(rp, (STRPTR)"AMIPHONE v0.1", 14);//skriver text ,14 antal tecken
}

void draw_scroll(struct RastPort* rp, int offset)
{
    char buffer[TEXTBUF_LEN];
    int len = strlen(scrollText);

    for (int i = 0; i < TEXTBUF_LEN - 1; i++) {
        buffer[i] = scrollText[(offset + i) % len];
    }
    buffer[TEXTBUF_LEN - 1] = '\0';

    SetAPen(rp, 0); // rensa raden
    RectFill(rp, 0, SCROLL_Y - 10, WIDTH - 1, SCROLL_Y + 2);//ritarr ?ver gammalt

    SetAPen(rp, 1);
    Move(rp, 10, SCROLL_Y);
    Text(rp, (STRPTR)buffer, strlen(buffer));//skriver ut scrollen
}

int main()
{
    //wb rutiner
    struct Screen* screen;
    struct Window* window;
    struct RastPort* rp;

    

    GfxBase = (struct GfxBase*)OpenLibrary("graphics.library", 0);
    IntuitionBase = (struct IntuitionBase*)OpenLibrary("intuition.library", 0);

    if (!GfxBase || !IntuitionBase)
        return 1;
    
    struct IntuiMessage* msg;

    //sk?rm o f?nsterinst 5=32f?rger
    screen = OpenScreenTags(NULL,
        SA_Depth, 5, 
        SA_Width, WIDTH,
        SA_Height, HEIGHT,
        SA_Title, (ULONG)"Amiphone",
        TAG_DONE);

    if (!screen)
        return 1;

    window = OpenWindowTags(NULL,
        WA_CustomScreen, (ULONG)screen,
        WA_Left, 0,
        WA_Top, 0,
        WA_Width, WIDTH,
        WA_Height, HEIGHT,
        WA_Flags, WFLG_BACKDROP | WFLG_BORDERLESS | WFLG_RMBTRAP | WFLG_ACTIVATE,
        WA_IDCMP, IDCMP_RAWKEY,
        TAG_DONE);

    if (!window) {
        CloseScreen(screen);
        return 1;
    }

    rp = window->RPort;

    draw_background(rp);

    // Rulltext-offset
    int scrollPos = 0;
    BOOL running = TRUE; //k?r loop

    //deklarera font
    struct TextAttr ta = {
       .ta_Name = "topaz.font", // detta ?r Topaz 8
       .ta_YSize = 8,
       .ta_Style = FS_NORMAL,
       .ta_Flags = FPF_ROMFONT
    };

    struct TextFont* font = OpenFont(&ta);
    if (font) {
        SetFont(rp, font); // anv?nd fonten

        Move(rp, 20, 20);
        Text(rp, "APhone", 6);


        Move(rp, 200, 20);
        Text(rp, "00:00", 5);

        CloseFont(font);
    }


    while (running) {


        while ((msg = (struct IntuiMessage*)GetMsg(window->UserPort))) { //l?s efter esc
            if (msg->Class == IDCMP_RAWKEY) {
                if (msg->Code == 0x45) { // ESC
                    running = FALSE;
                }
            }
            else if (msg->Class == IDCMP_CLOSEWINDOW) {
                running = FALSE;
            }
            ReplyMsg((struct Message*)msg);
        }

        //draw_scroll(rp, scrollPos++);

        //rita ikoner
        draw_icon(rp, 0, 50, 50);
        draw_icon(rp, 1, 145, 50);
        draw_icon(rp, 2, 240, 50);
        draw_icon(rp, 3, 50, 100);
        draw_icon(rp, 3, 145, 100);
        draw_icon(rp, 3, 240, 100);
        draw_icon(rp, 3, 50, 150);
        draw_icon(rp, 3, 145, 150);
        draw_icon(rp, 4, 240, 150);

       
        delay();
    }

    CloseWindow(window);
    CloseScreen(screen);
    //CloseLibrary(IntuitionBase);
    CloseLibrary((struct Library*)IntuitionBase);
    CloseLibrary((struct Library*)GfxBase);

    return 0;
}
